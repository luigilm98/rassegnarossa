function buildGoogleNewsFeed(locale: RadarLocale, query: RadarQuery) {
  const params = new URLSearchParams({
    q: `${locale.terms[query.id]} when:30d`,
    hl: locale.hl,
    gl: locale.gl,
    ceid: locale.ceid,
  });
  return `https://news.google.com/rss/search?${params.toString()}`;
}

